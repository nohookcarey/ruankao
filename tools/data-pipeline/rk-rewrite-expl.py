# 顺手的 OCR 错字（限定上下文，避免误伤）
TYPO = [
    ('数据厍', '数据库'),
    ('致们状态', '一致状态'),
    ('上下文有关文法、上下文有关文法', '上下文无关文法、上下文有关文法'),
    ('时间复杂度的紧致界', '时间复杂度的紧致界'),
]

STEM_FIX = {
    '2020L-65': [('表达式序列：n4, lgn, 2n, 1000n, n^(2/3), n!',
                  '表达式序列：n⁴, lg n, 2ⁿ, 1000n, n^(2/3), n!')],
}

done = []
for f in sorted(glob.glob('src/data/areas/*.json')):
    data = json.load(open(f, encoding='utf-8'))
    dirty = False
    for q in data:
        qid = q['id']
        if qid in EXPL:
            q['explanation'] = EXPL[qid]
            dirty = True
            done.append(qid)
        if qid in STEM_FIX:
            s = q.get('stem') or ''
            for a, b in STEM_FIX[qid]:
                s = s.replace(a, b)
            q['stem'] = s
            dirty = True
        e = q.get('explanation')
        if isinstance(e, str) and e:
            for a, b in TYPO:
                if a in e:
                    q['explanation'] = e.replace(a, b)
                    e = q['explanation']
                    dirty = True
    if dirty:
        with open(f, 'w', encoding='utf-8') as fh:
            json.dump(data, fh, ensure_ascii=False, indent=2)
            fh.write('\n')

print('重写解析', len(done), '道:', done)
